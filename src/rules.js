  function syl(ch, newJong) {
    const c = ch.charCodeAt(0) - 0xac00;
    return String.fromCharCode(0xac00 + c - (c % 28) + newJong);
  }

  function expand(rep, m) {
    if (typeof rep === 'function') return rep(m);
    return rep.replace(/\$(\d)/g, (_, n) => m[+n] || '');
  }

  function check(text) {
    const found = [];
    R.forEach((rule, order) => {
      rule.re.lastIndex = 0;
      let m;
      while ((m = rule.re.exec(text))) {
        if (m[0].length === 0) { rule.re.lastIndex++; continue; }
        if (rule.test && !rule.test(m, text)) continue;
        const rep = rule.rep == null ? null : expand(rule.rep, m);
        if (rep === m[0]) continue;
        found.push({ start: m.index, end: m.index + m[0].length, orig: m[0], rep, type: rule.type, msg: rule.msg, order, src: 'rule' });
      }
    });
    // 앞선 규칙 우선, 겹치는 것은 버림
    found.sort((a, b) => a.order - b.order || a.start - b.start);
    const kept = [];
    for (const f of found) if (!kept.some((k) => f.start < k.end && k.start < f.end)) kept.push(f);
    // 긴 문장 안내
    const sentRe = /[^.!?\n]+[.!?]?/g;
    let s;
    while ((s = sentRe.exec(text))) {
      const t = s[0].trim();
      if (t.replace(/\s/g, '').length > 90) {
        const off = s.index + s[0].indexOf(t);
        kept.push({ start: off, end: off + t.length, orig: t, rep: null, type: 'style', msg: '문장이 깁니다(공백 제외 ' + t.replace(/\s/g, '').length + '자). 두 문장으로 나누면 읽기 쉽습니다.', order: 9999, src: 'rule', long: true });
      }
    }
    return kept.sort((a, b) => a.start - b.start);
  }


